let i18nLang = 'en';
const i18nCurrent = () => i18nLang;
const i18nTag = () => (i18nLang === 'zh' ? 'zh-Hans' : i18nLang);

function t(key, vars) {
  const s = (I18N_LOCALES[i18nLang] || {})[key] ?? I18N_LOCALES.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m) : s;
}

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
}

function setLocale(lang, persist = true) {
  if (!I18N_LOCALES[lang]) lang = 'en';
  i18nLang = lang;
  document.documentElement.lang = i18nTag();
  document.documentElement.dir = I18N_META[lang].dir;
  if (persist) {
    try {
      localStorage.setItem('reelkeep.lang', lang);
    } catch {
      /* storage blocked */
    }
  }
  applyI18n();
  document.dispatchEvent(new CustomEvent('reelkeep:locale', { detail: { lang } }));
}

function i18nInit() {
  let lang = null;
  try {
    lang = localStorage.getItem('reelkeep.lang');
  } catch {
    /* storage blocked */
  }
  if (!lang || !I18N_LOCALES[lang]) {
    const nav = (navigator.languages || [navigator.language || 'en']).map((l) => String(l).toLowerCase());
    const hit = nav.find((l) => I18N_LOCALES[l] || I18N_LOCALES[l.split('-')[0]]);
    lang = hit ? (I18N_LOCALES[hit] ? hit : hit.split('-')[0]) : 'en';
  }
  setLocale(lang, false);
}

